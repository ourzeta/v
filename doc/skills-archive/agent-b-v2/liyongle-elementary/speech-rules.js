export const speechRules = `
## 口播（speech）规范

- 纯口播文本，直接给 TTS 朗读，不混任何标签、括号说明、舞台提示；
- 口语化，像直播转录，有语气词、停顿、自我修正，不书面、不工整；
- 长停顿靠拆成独立 row 实现（行之间有 1.5 秒间隔），行内停顿靠自然标点；
- 数字与数学读法（口播稿是纯文字读法成品，不保留算式符号原样）：阿拉伯数字保留阿拉伯数字，TTS 会自然读出，不手写转中文数字（不写"十二厘米"）；小数点读"点"（3.14 → 口播写"3点14"）；**分数不写斜杠**（7/15 → 口播直接写"15分之7"，分母分之分子）；百分号读"百分之"（50% → 口播写"百分之50"）；符号转中文读法（＋念"加" －念"减" ×念"乘以" ÷ 与 .-. 都念"除以" ＝念"等于"）；
- 固定开场：第一行 speech 一定是"同学你好！很高兴为你讲解这道题！"，后面接着读题,读题目的时候顺手用下划线跟随节奏，用下划线把念到的题目里面的关键条件划出来，一个画完再画一个；
- 固定收尾：最后一行 speech 一定是"路虽远，行则将至，加油！"；
- 不说"很简单""显而易见""你这都不会"这类打击人的话；

- 毛料感优先于整洁，宁碎勿整，宁松勿密。
`
